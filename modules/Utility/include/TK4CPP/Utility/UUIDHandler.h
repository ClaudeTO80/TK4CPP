/**
 * @file UUIDHandler.h
 * @brief Generation of RFC 9562 universally unique identifiers.
 * @since 0.1.0
 * @see https://www.rfc-editor.org/rfc/rfc9562
 */

#pragma once

#include <string>

#include "TK4CPP/Utility/Export.h"

namespace TK4CPP
{
    namespace Utility
    {
        /**
         * @class UUIDHandler
         * @brief Provides utility functions for generating UUIDs.
         *
         * All generators return the canonical lower-case textual form
         * (<tt>xxxxxxxx-xxxx-Vxxx-Nxxx-xxxxxxxxxxxx</tt>) and are thread-safe.
         */
        class TK4CPP_UTILITY_EXPORT UUIDHandler
        {
        public:
            /**
             * @brief Generates a random (version 4) UUID.
             * @return The UUID as a 36-character string.
             * @note Randomness comes from <tt>std::random_device</tt>.
             */
            static std::string Generate_V4();

            /**
             * @brief Generates a time-ordered (version 6) UUID.
             * @return The UUID as a 36-character string.
             * @details
             * The timestamp has a resolution of 100 ns. Values generated by the same process are
             * strictly increasing, so they sort lexicographically in generation order.
             * The node field is random (with the multicast bit set, as RFC 9562 requires
             * when the MAC address is not used).
             */
            static std::string Generate_V6();

            /**
             * @brief Generates a Unix-time-ordered (version 7) UUID.
             * @return The UUID as a 36-character string.
             * @details
             * The first 48 bits hold the Unix time in milliseconds. Values generated by the same
             * process are strictly increasing, so they sort lexicographically in generation order.
             */
            static std::string Generate_V7();
        };
    }
}
